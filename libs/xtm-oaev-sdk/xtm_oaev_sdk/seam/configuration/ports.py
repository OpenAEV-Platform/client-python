"""Configuration ports: the behaviour the public layer expects from the core.

``ConfigurationProtocol`` is the consumer-facing contract every configuration
service satisfies. The other protocols are the ports the public adapters
delegate to; the core implements them.
"""

from typing import Any, Protocol, runtime_checkable

from pydantic_settings import BaseSettings, PydanticBaseSettingsSource
from xtm_oaev_sdk.seam.configuration.models import (
    CONFIGURATION_TYPES,
    ConfigurationHint,
)

__all__ = [
    "ConfigurationProtocol",
    "ConfigurationResolverPort",
    "ConfigurationSourcesPort",
    "ConnectorSchemaPort",
    "SettingsSourcesPort",
    "TruthinessPort",
]


@runtime_checkable
class ConfigurationProtocol(Protocol):
    """Behavioral contract for configuration services.

    Any configuration implementation used by SDK consumers must satisfy
    this protocol. The built-in Configuration class implements it.

    Methods:
        get: Retrieve a typed configuration value by key.
        set: Override a configuration value at runtime.
        schema: Generate the connector configuration JSON schema.
    """

    def get(self, config_key: str) -> CONFIGURATION_TYPES:
        """Get configuration value by key."""
        ...

    def set(self, config_key: str, value: CONFIGURATION_TYPES) -> None:
        """Set a runtime override for a configuration key."""
        ...

    def schema(self) -> dict[str, Any]:
        """Generate the configuration JSON schema."""
        ...


@runtime_checkable
class TruthinessPort(Protocol):
    """Interprets the strings signalling a boolean value."""

    def is_truthy(self, value: str) -> bool:
        """Whether ``value`` signals True."""

    def is_falsy(self, value: str) -> bool:
        """Whether ``value`` signals False."""


@runtime_checkable
class ConfigurationSourcesPort(Protocol):
    """Reads raw configuration values from their backing stores."""

    def from_environment(self, env_var: str | None) -> str | None:
        """Value of an environment variable, None when unset or unnamed."""

    def from_dictionary(
        self, config_key_path: list[str] | None, source_dict: dict[str, Any]
    ) -> str | None:
        """Value at a two-level ``[section, key]`` path of a nested dict."""


@runtime_checkable
class ConfigurationResolverPort(Protocol):
    """Resolves configuration values from hints and loaded values."""

    def build_hints(
        self, config_hints: dict[str, dict[str, Any] | str]
    ) -> dict[str, ConfigurationHint]:
        """Hints from their definitions (a dict, or a bare default value)."""

    def load_values(
        self, config_values: dict[str, Any] | None, config_file_path: str
    ) -> dict[str, Any]:
        """Given values merged with the YAML file contents, when it exists."""

    def resolve(
        self, hint: ConfigurationHint, values: dict[str, Any]
    ) -> CONFIGURATION_TYPES:
        """Typed value of a hint: override, then env var, file, default."""

    def override(
        self,
        hints: dict[str, ConfigurationHint],
        config_key: str,
        value: CONFIGURATION_TYPES,
    ) -> None:
        """Set a runtime override, creating the hint when unknown."""

    def generate_schema(
        self, base_model: BaseSettings | None, schema_generator: type
    ) -> dict[str, Any]:
        """Connector configuration JSON schema of ``base_model``."""


@runtime_checkable
class ConnectorSchemaPort(Protocol):
    """Transforms a pydantic JSON schema into a connector manifest schema."""

    def dereference_schema(self, schema_with_refs: dict[str, Any]) -> dict[str, Any]:
        """Schema with every internal ``$ref`` inlined."""

    def flatten_config_loader_schema(
        self, root_schema: dict[str, Any]
    ) -> dict[str, Any]:
        """Schema with every config variable at root level."""

    def filter_schema(self, schema: dict[str, Any]) -> dict[str, Any]:
        """Schema without the attributes generated by the platform."""

    def finalize(self, json_schema: dict[str, Any], dialect: str) -> dict[str, Any]:
        """Flat, dereferenced, filtered manifest schema."""

    def collapse_nullable(self, inner_json_schema: dict[str, Any]) -> dict[str, Any]:
        """Schema of a nullable field, without ``anyOf``."""


@runtime_checkable
class SettingsSourcesPort(Protocol):
    """Chooses where settings are loaded from, in priority order."""

    def select_sources(
        self,
        settings_cls: type[BaseSettings],
        env_settings: PydanticBaseSettingsSource,
    ) -> tuple[PydanticBaseSettingsSource, ...]:
        """Environment variables first, then the YAML or .env file found."""
